#!/usr/bin/env python3
"""Assemble web/index.html + core.js + analytics.js + mlmodel.js + qrcode.min.js + ui.js + alarms.js + ext.js
   -> web/dist.html  and  CardioRespMonitor/webpage.h (gzip-compressed, served with Content-Encoding: gzip)"""
import re, sys, gzip, pathlib
root = pathlib.Path(__file__).parent
rd = lambda n: (root / "web" / n).read_text()
html = rd("index.html")
core = rd("core.js") + "\n" + rd("analytics.js") + "\n" + rd("mlmodel.js") + "\n" + rd("qrcode.min.js")
ui = rd("ui.js")
ext = rd("ext.js")
alarm = rd("alarms.js")
for m in ("/*__CORE__*/", "/*__UI__*/", "/*__ALARM__*/", "/*__EXT__*/"):
    assert m in html, m
for name, src in (("core", core), ("ui", ui), ("alarm", alarm), ("ext", ext)):
    assert src.count("</script") == 0, name + " contains a closing script tag"
out = html.replace("/*__CORE__*/", core).replace("/*__UI__*/", ui).replace("/*__ALARM__*/", alarm).replace("/*__EXT__*/", ext)
(root / "web/dist.html").write_text(out)
raw = out.encode("utf-8")
gz = gzip.compress(raw, 9, mtime=0)
lines = []
for i in range(0, len(gz), 24):
    lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 24]))
hdr = ("// Auto-generated by tools_build_page.py from web/index.html, core.js, analytics.js, mlmodel.js, ui.js, alarms.js, ext.js\n"
       "// The page is stored gzip-compressed and sent with Content-Encoding: gzip. Edit web/ and re-run the script.\n"
       "#pragma once\n#include <pgmspace.h>\n\n"
       "#define INDEX_HTML_GZ_LEN %d\n#define INDEX_HTML_RAW_LEN %d\n"
       "static const uint8_t INDEX_HTML_GZ[INDEX_HTML_GZ_LEN] PROGMEM = {\n" % (len(gz), len(raw)) + ",\n".join(lines) + "\n};\n")
(root / "CardioRespMonitor/webpage.h").write_text(hdr)
print("dist.html %d bytes, gzip %d bytes (%.0f %%); webpage.h written" % (len(raw), len(gz), 100.0 * len(gz) / len(raw)))
