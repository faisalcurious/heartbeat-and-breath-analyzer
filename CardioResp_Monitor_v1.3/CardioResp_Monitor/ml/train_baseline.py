"""
train_baseline.py - trains the tiny MLP (21 -> 14 -> 7) on synthetic data and writes
  CardioRespMonitor/MlModel.h   (firmware)
  web/mlmodel.js                (dashboard, in-page inference)
  ml/model.json                 (readable copy)
Run:  python3 ml/train_baseline.py
The Colab notebook produces the same three files from REAL data.
"""
import json, os, sys, numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from cr_features import N_IN, N_CLASS, CLASS_NAMES, FEATURE_NAMES
from cr_synth import dataset
from sklearn.neural_network import MLPClassifier

HID = 14
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def export(W1, b1, W2, b2, info, root=ROOT):
    m = dict(version=info.get("version", "baseline-synthetic-1"), n_in=N_IN, n_hid=len(b1), n_class=N_CLASS,
             classes=CLASS_NAMES, features=FEATURE_NAMES, W1=np.round(W1, 5).tolist(), b1=np.round(b1, 5).tolist(),
             W2=np.round(W2, 5).tolist(), b2=np.round(b2, 5).tolist(), info=info)
    with open(os.path.join(root, "ml", "model.json"), "w") as f: json.dump(m, f, indent=1)
    with open(os.path.join(root, "web", "mlmodel.js"), "w") as f:
        f.write("// generated by ml/train_baseline.py (or the Colab notebook) - do not edit\n")
        f.write("const ML_MODEL = " + json.dumps(m, separators=(",", ":")) + ";\n")
        f.write('if (typeof module !== "undefined") module.exports = ML_MODEL;\n')
    def arr(name, a):
        a = np.asarray(a)
        if a.ndim == 1: return f"static const float {name}[{a.shape[0]}] PROGMEM = {{" + ",".join(f"{v:.5f}f" for v in a) + "};\n"
        rows = ",\n  ".join("{" + ",".join(f"{v:.5f}f" for v in r) + "}" for r in a)
        return f"static const float {name}[{a.shape[0]}][{a.shape[1]}] PROGMEM = {{\n  {rows}}};\n"
    with open(os.path.join(root, "CardioRespMonitor", "MlModel.h"), "w") as f:
        f.write("// generated by ml/train_baseline.py (or the Colab notebook) - do not edit\n#pragma once\n#include <pgmspace.h>\n")
        f.write(f'#define ML_VERSION "{m["version"]}"\n#define ML_N_IN {N_IN}\n#define ML_N_HID {len(b1)}\n#define ML_N_CLASS {N_CLASS}\n')
        f.write(arr("ML_W1", W1) + arr("ML_B1", b1) + arr("ML_W2", W2) + arr("ML_B2", b2))
    return m


if __name__ == "__main__":
    Xtr, ytr = dataset(60000, seed=11)
    Xte, yte = dataset(15000, seed=99)
    clf = MLPClassifier(hidden_layer_sizes=(HID,), activation="relu", alpha=2e-3, max_iter=400,
                        early_stopping=True, n_iter_no_change=15, random_state=3)
    clf.fit(Xtr, ytr)
    acc = clf.score(Xte, yte)
    from sklearn.metrics import confusion_matrix, classification_report
    pred = clf.predict(Xte)
    print("test accuracy (synthetic):", round(acc, 4))
    print(classification_report(yte, pred, target_names=CLASS_NAMES, digits=3))
    print(confusion_matrix(yte, pred))
    W1 = clf.coefs_[0].T; b1 = clf.intercepts_[0]; W2 = clf.coefs_[1].T; b2 = clf.intercepts_[1]
    export(W1, b1, W2, b2, dict(version="baseline-synthetic-1", trained_on="synthetic physiological feature distributions",
                                n_train=len(ytr), test_accuracy_synthetic=round(float(acc), 4)))
    print("params:", W1.size + b1.size + W2.size + b2.size)
